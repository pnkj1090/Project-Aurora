"""
Domain models for Phase 5L.1 — Memory Candidate Extraction.
Defines ModelCandidateProposal, CandidateExtractionResponse,
CandidateValidationResult, and validated MemoryCandidate.

CRITICAL INVARIANTS:
1. MemoryCandidate != MemoryItem.
2. Candidate extraction is NOT memory persistence.
3. No SQLite writes or MemoryStore operations.
4. Model proposals are strictly separated from accepted candidates.
"""
from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional
from pydantic import BaseModel, Field

from app.services.memory.schemas import MemoryType


class CandidateEvidenceType(str, Enum):
    """
    Evidence classification for memory candidates.
    USER_EXPLICIT: Directly asserted by user in their own words.
    MODEL_INFERRED: Inferred tendency/habit; not directly asserted.
    """
    USER_EXPLICIT = "user_explicit"
    MODEL_INFERRED = "model_inferred"


class CandidateSensitivity(str, Enum):
    """
    Conservative sensitivity classification for memory candidates.
    NORMAL: Routine preferences, non-sensitive personal facts.
    SENSITIVE: Health, financial, relationship, or private context.
    """
    NORMAL = "normal"
    SENSITIVE = "sensitive"


class TemporalAnchor(BaseModel):
    """
    Preserves temporal, conditional, or transitory framing of a statement.
    Prevents normalizing time-bound qualifiers into absolute permanent facts.
    """
    is_temporary: bool = False
    is_hypothetical: bool = False
    timeframe: Optional[str] = None
    qualifier_phrase: Optional[str] = None


class ModelCandidateProposal(BaseModel):
    """
    Raw candidate proposal generated by the extraction model.
    STRICTLY excludes server metadata: no candidate_id, user_id,
    conversation_id, timestamps, turn_index, or lifecycle status.
    """
    memory_type: MemoryType
    content: str = Field(min_length=3, max_length=500, description="Proposed memory text")
    evidence_type: CandidateEvidenceType
    confidence: float = Field(ge=0.0, le=1.0, description="Model confidence score")
    importance: int = Field(default=3, ge=1, le=5, description="Importance scale 1-5")
    user_quote: Optional[str] = Field(default=None, description="Verbatim quote from user message")
    temporal: Optional[TemporalAnchor] = None
    sensitivity: CandidateSensitivity = CandidateSensitivity.NORMAL
    tags: List[str] = Field(default_factory=list)


class CandidateExtractionResponse(BaseModel):
    """
    Structured response schema expected from AI provider extraction prompt.
    Contains zero chain-of-thought or reasoning fields.
    """
    proposals: List[ModelCandidateProposal] = Field(default_factory=list)


class MemoryCandidate(BaseModel):
    """
    Accepted, server-validated memory candidate.
    Contains ONLY validated information.
    CRITICAL: Does NOT contain is_valid or rejection_reason.
    """
    # Server-controlled authoritative identity & provenance
    candidate_id: str = Field(description="Server-generated unique candidate ID: cand_<12hex>")
    user_id: str = Field(description="Server-stamped active user identity")
    conversation_id: str = Field(description="Server-stamped conversation ID")
    turn_index: int = Field(default=0, description="Turn index within conversation")
    extracted_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    extractor_version: str = Field(default="5L.1")

    # Validated candidate fields
    memory_type: MemoryType
    content: str
    evidence_type: CandidateEvidenceType
    confidence: float
    importance: int
    tags: List[str] = Field(default_factory=list)
    user_quote: Optional[str] = None
    temporal: Optional[TemporalAnchor] = None
    sensitivity: CandidateSensitivity = CandidateSensitivity.NORMAL


class CandidateValidationResult(BaseModel):
    """
    Internal diagnostic object produced by CandidateValidationPipeline.
    Separates rejected proposals from accepted MemoryCandidate objects.
    This object is internal-only and NEVER exposed through public APIs.
    """
    proposal: ModelCandidateProposal
    is_valid: bool
    rejection_reason: Optional[str] = None
    validation_errors: List[str] = Field(default_factory=list)
    candidate: Optional[MemoryCandidate] = None
