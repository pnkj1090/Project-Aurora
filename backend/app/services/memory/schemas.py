import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field, field_validator


class MemoryType(str, Enum):
    """
    Conceptual types of memories retained by Project Aurora.
    """
    EXPLICIT = "explicit"       # Directly stated instructions ("Remember that...")
    PREFERENCE = "preference"   # User preferences, habits, likes/dislikes
    FACT = "fact"               # Objective truths about the user
    COMMITMENT = "commitment"   # Promises or ongoing obligations
    TASK = "task"               # High-level tracking notes
    EPISODIC = "episodic"       # Significant past events or conversations


class MemorySource(str, Enum):
    """
    Provenance of a memory item to maintain strict privacy boundaries.
    """
    USER_EXPLICIT = "user_explicit"  # Explicitly directed by the user via tool or UI (Confidence: 1.0)
    INFERRED = "inferred"            # Deduced by Aurora during conversation (Requires confirmation/review)
    SYSTEM = "system"                # Generated by Aurora system components


class MemoryStatus(str, Enum):
    """
    Lifecycle status allowing separation of active, pending, and archived memories.
    """
    ACTIVE = "active"                   # Confirmed and actively injected into context
    PENDING_REVIEW = "pending_review"   # Inferred; awaiting user inspection or confirmation
    ARCHIVED = "archived"               # Soft-deleted or obsolete memory


class MemoryLifecycleState(str, Enum):
    """
    Deterministic lifecycle evaluation states for MemoryItem.
    Precedence: SOFT_DELETED > ARCHIVED > EXPIRED > ACTIVE.
    """
    ACTIVE = "active"
    EXPIRED = "expired"
    ARCHIVED = "archived"
    SOFT_DELETED = "soft_deleted"


class MemoryItem(BaseModel):
    """
    Core memory representation for Project Aurora.
    Fully provider-agnostic and timezone-aware (stored in UTC).
    """
    id: str = Field(default_factory=lambda: f"mem_{uuid.uuid4().hex[:10]}")
    type: MemoryType
    content: str = Field(min_length=1, max_length=5000, description="The memory text.")
    importance: int = Field(default=3, ge=1, le=5, description="Importance scale from 1 (trivial) to 5 (critical).")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0, description="Confidence score.")
    source: MemorySource = Field(default=MemorySource.USER_EXPLICIT)
    status: MemoryStatus = Field(default=MemoryStatus.ACTIVE)

    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
    expires_at: Optional[datetime] = Field(default=None, description="Optional UTC expiration datetime.")

    tags: List[str] = Field(default_factory=list, description="Categorization tags.")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Extensible metadata.")
    is_active: bool = Field(default=True, description="Lifecycle active flag.")

    @field_validator("created_at", "updated_at", "expires_at", mode="after")
    @classmethod
    def ensure_utc(cls, v: Optional[datetime]) -> Optional[datetime]:
        """Ensure all timestamps are timezone-aware in UTC."""
        if v is None:
            return None
        if v.tzinfo is None:
            return v.replace(tzinfo=timezone.utc)
        return v.astimezone(timezone.utc)

    @property
    def user_id(self) -> Optional[str]:
        """Server-controlled active user identity from metadata."""
        return self.metadata.get("user_id")

    def is_expired_at(self, now: Optional[datetime] = None) -> bool:
        """
        Determines if the memory has passed its expiration datetime relative to `now`.
        Boundary rule: now == expires_at is ACTIVE; expires iff now > expires_at.
        """
        if self.expires_at is None:
            return False
        current = now or datetime.now(timezone.utc)
        if current.tzinfo is None:
            current = current.replace(tzinfo=timezone.utc)
        exp = self.expires_at if self.expires_at.tzinfo else self.expires_at.replace(tzinfo=timezone.utc)
        return current > exp

    @property
    def is_expired(self) -> bool:
        """Determines if the memory has passed its expiration datetime at current wall-clock UTC."""
        return self.is_expired_at()

    def mark_archived(self) -> None:
        """Convenience method to soft-delete / archive memory."""
        self.status = MemoryStatus.ARCHIVED
        self.is_active = False
        self.updated_at = datetime.now(timezone.utc)


def evaluate_lifecycle_state(item: MemoryItem, now: Optional[datetime] = None) -> MemoryLifecycleState:
    """
    Authoritative, deterministic read-only lifecycle state evaluation.
    Precedence: SOFT_DELETED > ARCHIVED > EXPIRED > ACTIVE.
    """
    if not item.is_active:
        return MemoryLifecycleState.SOFT_DELETED
    if item.status == MemoryStatus.ARCHIVED:
        return MemoryLifecycleState.ARCHIVED
    if item.is_expired_at(now):
        return MemoryLifecycleState.EXPIRED
    return MemoryLifecycleState.ACTIVE

